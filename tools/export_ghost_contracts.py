"""Export Pydantic schemas and TypeScript types from one contract source."""
from __future__ import annotations
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ghost_director.domain import models


def ts(node):
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    if "anyOf" in node:
        return " | ".join(ts(n) for n in node["anyOf"])
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(n) for n in node["enum"])
    kind = node.get("type")
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(ts(n) for n in node["prefixItems"]) + "]"
        return f"Array<{ts(node.get('items', {}))}>"
    if kind == "object":
        return f"Record<string, {ts(node.get('additionalProperties', {})) if isinstance(node.get('additionalProperties'), dict) else 'any'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "any")


schemas = {}; definitions = {}
for name in ["Material", "Entity", "Camera", "Room", "SceneRevision", "EntityPatch", "ShotPlan", "Artifact", "AgentTask", "Observation", "Take", "Event", "Command", "Snapshot"]:
    schemas[name] = getattr(models, name).model_json_schema()
    definitions.update(schemas[name].get("$defs", {}))
    definitions[name] = schemas[name]
output = ROOT / "contracts/ghost-director"
output.mkdir(parents=True, exist_ok=True)
(output / "schemas.json").write_text(json.dumps(schemas, indent=2) + "\n")
lines = ["// Generated by tools/export_ghost_contracts.py. Do not edit."]
for name, schema in sorted(definitions.items()):
    lines.append(f"export interface {name} {{")
    required = set(schema.get("required", []))
    for key, value in schema.get("properties", {}).items():
        # Validated serialized output contains defaults; nullable values remain nullable.
        optional = "" if key in required or "default" in value else "?"
        lines.append(f"  {key}{optional}: {ts(value)};")
    lines.append("}\n")
target = ROOT / "web/src/api/contracts.ts"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(lines))
print(f"Exported {len(schemas)} contracts")
